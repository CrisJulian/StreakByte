import type { ArenaScenario } from '../domain/rules/arenaQuestions';

function scenario(
  id: string,
  track: 'hw' | 'net',
  topic: string,
  prompt: string,
  choices: ArenaScenario['choices'],
  correctIndex: ArenaScenario['correctIndex'],
  explanation: string,
): ArenaScenario {
  return { id, track, topic, prompt, choices, correctIndex, explanation };
}

